# server/core/schemas.py
# =============================================================================
# Pydantic Schemas for DS Workflow Backend - Modular Architecture
# =============================================================================
# Defines strict, FinServ-grade request/response schemas for all steps:
#
#   • Dataset upload (Step01)
#   • Column selections / metadata
#   • Step06 balanced & split dataset
#   • Step07 model training configuration
#   • Step08 evaluation metrics
#
# All future model documentation, fairness, stability, and audit trails will
# extend these schemas.
# =============================================================================

from __future__ import annotations
from pydantic import BaseModel, Field
from typing import List, Dict, Any, Optional


# -----------------------------------------------------------------------------
# Step01: Dataset Upload
# -----------------------------------------------------------------------------
class DatasetUploadResponse(BaseModel):
    ok: bool
    n_rows: int
    n_cols: int
    columns: List[str]


# -----------------------------------------------------------------------------
# Column Selection / Metadata
# -----------------------------------------------------------------------------
class ColumnSelection(BaseModel):
    numeric_columns: List[str] = Field(default_factory=list)
    categorical_columns: List[str] = Field(default_factory=list)
    target_column: Optional[str] = None


# -----------------------------------------------------------------------------
# Step06: Train/Test Split & Balancing Configuration
# -----------------------------------------------------------------------------
class SplitConfig(BaseModel):
    test_size: float = Field(..., description="Proportion of test data (e.g., 0.25)")
    balance_method: Optional[str] = Field(
        None,
        description="Optional balancing technique: 'none', 'smote', 'undersample', etc."
    )
    target: str = Field(..., description="Target column name")


class SplitPayload(BaseModel):
    """
    This payload contains the actual split datasets generated by Step06.
    The frontend will send pandas-compatible JSON.
    """
    X_train: List[Dict[str, Any]]
    X_test: List[Dict[str, Any]]
    y_train: List[Any]
    y_test: List[Any]
    target: str


# -----------------------------------------------------------------------------
# Step07: Model Training Request
# -----------------------------------------------------------------------------
class TrainRequest(BaseModel):
    models: List[str] = Field(
        ...,
        description="List of model identifiers: ['logreg', 'rf', 'xgb', ...]"
    )
    # Future hooks for hyperparameter overrides can be added here:
    # params: Dict[str, Any] = Field(default_factory=dict)


# -----------------------------------------------------------------------------
# Step07/08: Metrics Structures
# -----------------------------------------------------------------------------
class MetricSummary(BaseModel):
    auc: Optional[float] = None
    pr_auc: Optional[float] = None
    accuracy: Optional[float] = None
    precision: Optional[float] = None
    recall: Optional[float] = None
    f1: Optional[float] = None
    ks: Optional[float] = None
    gini: Optional[float] = None
    confusion_matrix: Optional[List[List[int]]] = None


class ModelResult(BaseModel):
    model_name: str
    metrics: MetricSummary
    feature_importance: Optional[Dict[str, float]] = None


class TrainingResponse(BaseModel):
    ok: bool
    results: List[ModelResult]


# -----------------------------------------------------------------------------
# Step08: Evaluation Request
# -----------------------------------------------------------------------------
class EvaluationResponse(BaseModel):
    ok: bool
    results: Dict[str, Any]
    message: str = "Evaluation completed."


# -----------------------------------------------------------------------------
# Health Check
# -----------------------------------------------------------------------------
class HealthResponse(BaseModel):
    ok: bool
    message: str

