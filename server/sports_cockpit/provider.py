"""Generic probabilistic PA provider — decouples the whole-game simulator from D3.

The Phase 5 whole-game kernel (`build_game_contribs` + `simulate_game`) consumes a PA scorer
through exactly three additive-logit operations: ``batter_contrib(raw)``, ``pitcher_contrib(raw)``,
and ``context_base_logits(inning, tb, outs, base, score_diff)``. Any multinomial-logistic model
decomposes into that protocol, so a cockpit-trained logistic challenger on the static feature
view is simulator-eligible through the *unchanged* kernel — no D3-specific path.

This module provides:
  * `PROBABILISTIC_PA_PROVIDER_V1` — the governed contract (documented invariants).
  * `classify_feature` / `simulator_eligibility` — per-feature availability and eligibility gate.
  * `StaticStateResolver` — resolves a player's static prior-season feature vector by uuid+season.
  * `CockpitLinearFold` — a fold (duck-typed to FastD3Fold) built from a cockpit logistic model,
    proven to reproduce the model's `predict_proba` to floating tolerance.

The D3 authority is *not* modified; this is a parallel generic path added alongside it.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any, Mapping, Sequence

import numpy as np
