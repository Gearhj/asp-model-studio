import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

const ROOT = new URL("..", import.meta.url);
const read = (path) => readFile(new URL(path, ROOT), "utf8");

const [client, panel, stageContent, workflow, workflowState] = await Promise.all([
  read("src/sports/workflow/currentGoldDataReview.ts"),
  read("src/sports/workflow/CurrentGoldDataReviewPanel.tsx"),
  read("src/sports/workflow/GuidedStageContent.tsx"),
  read("src/sports/workflow/GuidedWorkflow.tsx"),
  read("src/sports/workflow/workflowState.ts"),
]);

const stage2Content = stageContent.slice(
  stageContent.indexOf("case 2:"),
  stageContent.indexOf("case 3:"),
);

test("Stage 2 reads the project-scoped current-Gold review rather than the legacy cockpit preview", () => {
  assert.match(
    client,
    /\/projects\/\$\{encodeURIComponent\(projectId\)\}\/sports\/stage2-data-review/,
  );
  assert.doesNotMatch(client, /\/sports\/datasets\/active|\/cockpit\/data-preview/);
  assert.ok(workflow.includes("useProjectCurrentGoldDataReview(projectId"));
  assert.ok(stage2Content.includes("CurrentGoldDataReviewPanel"));
  assert.ok(!stage2Content.includes("DataPreviewPanel"));
});

test("Stage 2 surfaces the exact current-Gold population and ordered feature contract", () => {
  assert.ok(panel.includes("Project-linked materialization authority"));
  assert.ok(panel.includes("review.sourceAuthority.registrationId"));
  assert.ok(panel.includes("review.sourceAuthority.datasetVersionId"));
  assert.ok(panel.includes("review.sourceAuthority.manifestSha"));
  assert.ok(panel.includes("review.goldAuthority.manifestSha"));
  assert.ok(panel.includes("Exact ordered 48 predictors"));
  assert.ok(panel.includes("required 2023–2026"));
  assert.ok(
    panel.includes('value={int(review.matrix.finalOot.rows)}'),
    "the required 14,067 final-OOT count must render from verified review evidence",
  );
  assert.ok(panel.includes("review.matrix.finalOot.startDate"));
  assert.ok(panel.includes("review.matrix.finalOot.endDate"));
  // Counts and dates come from the verified response; the UI must not substitute legacy literals.
  assert.ok(panel.includes("review.matrix.predictorCount"));
  assert.ok(panel.includes("review.matrix.seasons.join"));
  assert.doesNotMatch(stage2Content, /MLB_PA_V1|MLB_PA_FEATURE_VIEW_V1|DataPreviewPanel/);
});

test("the five conditional PA fields are presented as simulator-generated state", () => {
  assert.ok(client.includes('"SIMULATION_GENERATED_STATE"'));
  assert.ok(panel.includes('item.classification === "SIMULATION_GENERATED_STATE"'));
  assert.ok(panel.includes("These five predictors may train the conditional PA model"));
  assert.ok(panel.includes("forecast-time values must be generated by the simulator"));
  assert.ok(panel.includes("Future actual game state is prohibited"));
});

test("predictor missingness exposes every required diagnostic without treating indicators as completeness", () => {
  for (const field of [
    "overallMissingPct",
    "developmentMissingPct",
    "finalOotMissingPct",
    "indicatorPrevalence",
    "affectedRows",
    "affectedPlayerCount",
    "reasonCounts",
    "bySeason",
    "byMonth",
  ]) {
    assert.ok(client.includes(field), `missing Stage 2 diagnostic field: ${field}`);
  }
  for (const label of [
    "Predictor missingness diagnostics",
    "Indicator prevalence",
    "Affected rows",
    "Season / month",
  ]) {
    assert.ok(panel.includes(label), `missing Stage 2 diagnostic surface: ${label}`);
  }
  assert.ok(panel.includes("review.missingness.note"));
  assert.ok(panel.includes("item.reasonCounts"));
  assert.ok(panel.includes("item.bySeason") && panel.includes("item.byMonth"));
});

test("acceptance fails closed and the adopted review is bound to exact source and Gold identities", () => {
  assert.ok(panel.includes("review.acceptance.allowed"));
  assert.ok(panel.includes("review.acceptance.blockers"));
  assert.ok(workflow.includes("stage2ReviewMatchesBinding(currentGoldReview, binding)"));
  assert.ok(workflow.includes("!currentGoldReview.review?.acceptance.allowed"));
  assert.ok(workflow.includes("disabledReason={stage2AcceptanceReason(currentGoldReview, binding)}"));
  assert.ok(workflow.includes("acceptStage2DataReview(projectId, binding, currentGoldReview.review)"));

  for (const helper of [
    "loadStage2DataReviewAcceptance",
    "stage2DataReviewAcceptanceMatches",
    "acceptStage2DataReview",
    "invalidateStage2DataReview",
  ]) {
    assert.ok(workflowState.includes(helper), `missing identity-bound Stage 2 helper: ${helper}`);
  }

  for (const identity of [
    "registrationId",
    "sourceManifestSha",
    "goldManifestSha",
    "reviewDigest",
  ]) {
    assert.ok(workflowState.includes(identity), `Stage 2 adoption is not bound to ${identity}`);
  }
  assert.ok(workflowState.includes("accepted.registrationId === binding.registrationId"));
  assert.ok(workflowState.includes("accepted.datasetVersionId === binding.datasetVersionId"));
  assert.ok(workflowState.includes("accepted.sourceManifestSha === binding.manifestSha"));
});
